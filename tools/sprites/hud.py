ASCENT, DESCENT = 3, 2  # linhas livres acima (acento) e abaixo (cedilha) do corpo 5x7
CELL_W, CELL_H = 7, ASCENT + 7 + DESCENT + 2  # + 1 px de contorno em cima e embaixo

# Mini avião (mesmo desenho e cores do jogador, simplificado)
LIFE = [
    "....Y....",
    "...YBY...",
    "...YlY...",
    ".YYYlYYY.",
    "YYYYlYYYY",
    "yyyYlYyyy",
    "...YlY...",
    "..YYlYY..",
    "..yyyyy..",
]


def font_atlas() -> list[str]:
    c = blank(CELL_W * len(CHARSET), CELL_H)
    for n, ch in enumerate(CHARSET):
        glyph = GLYPHS[ch]
        if len(glyph) == 7:  # só o corpo: acento e cedilha vazios
            glyph = ["....."] * ASCENT + glyph + ["....."] * DESCENT
        assert len(glyph) == ASCENT + 7 + DESCENT and all(len(r) == 5 for r in glyph), ch
        for y, row in enumerate(glyph):
            body_y = y - ASCENT  # 0..6 dentro do corpo
            for x, px in enumerate(row):
                if px == "#":
                    # luz de cima: acento claro, base do corpo e cedilha em cinza
                    c[1 + y][n * CELL_W + 1 + x] = "S" if body_y >= 5 else "w"
    return to_rows(outline(c))


def life_icon() -> list[str]:
    c = blank(11, 11)
    for y, row in enumerate(LIFE):
        for x, px in enumerate(row):
            if px != ".":
                c[1 + y][1 + x] = px
    return to_rows(outline(c))


assert sorted(GLYPHS) == sorted(CHARSET), "CHARSET e GLYPHS diferentes"
FRAMES = {"font": font_atlas(), "life": life_icon()}

